export function cardEffectCopy(id, golden = false) {
  const entry = effects[id];
  if (!entry) return '';
  const [base, extra] = Array.isArray(entry) ? entry : [entry.base ?? entry];
  const copy = golden ? entry.golden ?? [base, extra].filter(Boolean).join(' ') : base;
  return copy.replace(/\{(\d+)\/(\d+)\}/g, (_, normal, upgraded) => golden ? upgraded : normal);
}

export function effectParts(copy) {
  const parts = [];
  let end = 0;
  for (const match of copy.matchAll(/\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g)) {
    if (match.index > end) parts.push({ text: copy.slice(end, match.index) });
    const [, term, label = term] = match;
    parts.push({ term, text: label });
    end = match.index + match[0].length;
  }
  if (end < copy.length) parts.push({ text: copy.slice(end) });
  return parts;
}
