export function weaponProfile(unit, oldStyle) {
  const name = unit.name, role = unit.role ?? unit.hint ?? '';
  const type = explicit[unit.id]
    ?? (unit.form === '동물형' || /^(?:순록 새끼|들멧돼지|잿빛 오소리|얼룩 스라소니|황갈색 족제비)$/.test(name) ? 'beast' : null)
    ?? (/방패|가지 경비|세계수 파수꾼|진료소 수비대장/.test(name) ? 'shield' : null)
    ?? (/투창/.test(name) ? 'javelin' : null)
    ?? (/석궁|총잡이|총 경비|포수|포격|석조 사수|포신|투척|투석/.test(name) ? 'launcher' : null)
    ?? (/궁수|명사수|화살|활잡이/.test(name) ? 'bow' : null)
    ?? (/검사|검병|검무|보조검|검사수|단검/.test(name) ? 'sword' : null)
    ?? (/창병|창수|창잡이/.test(name) ? 'spear' : null)
    ?? (/주먹|권사|격투/.test(name) ? 'fist' : null)
    ?? (/사제|마법|주술|지팡이/.test(name) ? 'staff' : null)
    ?? (/나팔|징지기|북잡이|신호|종지기|종 타주/.test(name) ? 'signal' : null)
    ?? (/망치|대장장이|도끼|집게|정비공/.test(name) ? 'tool' : null)
    ?? (oldStyle === 'ranged' || /^원거리/.test(role) ? 'launcher' : null)
    ?? (oldStyle === 'animal' ? 'beast' : null)
    ?? (oldStyle === 'machine' ? 'machine' : null)
    ?? (oldStyle === 'support' ? 'signal' : null)
    ?? 'tool';
  return { type, attacks: choices[type] };
}

