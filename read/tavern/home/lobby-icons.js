export function drawTavernIcon(canvas, name) {
  const sprite = sprites[name];
  canvas.width = canvas.height = sprite.length;
  const context = canvas.getContext('2d');
  sprite.forEach((row, y) => {
    [...row].forEach((pixel, x) => {
      if (pixel === '.') return;
      context.fillStyle = palette[pixel];
      context.fillRect(x, y, 1, 1);
    });
  });
}

for (const canvas of document.querySelectorAll('.lobby canvas[data-icon]')) {
  drawTavernIcon(canvas, canvas.dataset.icon);
}
